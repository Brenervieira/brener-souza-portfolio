from sklearn.model_selection import KFold
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from statsmodels.nonparametric.kernel_regression import KernelReg
import numpy as np
import pandas as pd

df_kernel_cv = df.sample(n=1000, random_state=42)

X = df_kernel_cv.drop(columns=["MedHouseVal"])
y = df_kernel_cv["MedHouseVal"]

kf = KFold(n_splits=3, shuffle=True, random_state=42)

resultados_kernel = []

for fold, (train_idx, test_idx) in enumerate(kf.split(X), start=1):
    print(f"Rodando fold {fold}")

    X_train_fold = X.iloc[train_idx]
    X_test_fold = X.iloc[test_idx]
    y_train_fold = y.iloc[train_idx]
    y_test_fold = y.iloc[test_idx]

    kr = KernelReg(
        endog=y_train_fold,
        exog=X_train_fold,
        var_type="c" * X_train_fold.shape[1]
    )

    y_pred, _ = kr.fit(X_test_fold)

    mae = mean_absolute_error(y_test_fold, y_pred)
    mse = mean_squared_error(y_test_fold, y_pred)
    rmse = np.sqrt(mse)
    r2 = r2_score(y_test_fold, y_pred)

    resultados_kernel.append({
        "Fold": fold,
        "MAE": mae,
        "MSE": mse,
        "RMSE": rmse,
        "R2": r2
    })

resultados_kernel_df = pd.DataFrame(resultados_kernel)

resultados_kernel_df

resultados_kernel_df.describe()

"""Inicialmente foi planejado o uso de bootstrap para avaliar a estabilidade da Kernel Regression. No entanto, devido ao alto custo computacional do método, a validação foi substituída por K-Fold Cross Validation com 3 folds em uma amostra reduzida de 1000 observações. Essa abordagem permite avaliar a variação das métricas preditivas em diferentes divisões dos dados, mantendo a viabilidade computacional do experimento.

## Testes Não Paramétricos
"""

df["HouseAge"].describe()

novos = df[df["HouseAge"] <= 18]["MedHouseVal"]
antigos = df[df["HouseAge"] >= 37]["MedHouseVal"]

from scipy.stats import mannwhitneyu

stat, p = mannwhitneyu(novos, antigos)

print(f"Estatística U: {stat:.4f}")
print(f"P-valor: {p:.6f}")

alpha = 0.05

if p < alpha:
    print("Rejeitamos H0")
    print("Existe diferença estatisticamente significativa entre imóveis novos e antigos.")
else:
    print("Não rejeitamos H0")
    print("Não há evidências de diferença estatisticamente significativa entre os grupos.")

print(novos.median())
print(antigos.median())

"""O teste de Mann-Whitney indicou diferença estatisticamente significativa entre os preços dos imóveis classificados como novos e antigos (p < 0,001). Os imóveis antigos apresentaram mediana de preço superior (1,864) em comparação aos imóveis novos (1,673), sugerindo que a idade do imóvel está associada a diferenças na distribuição dos preços."""

